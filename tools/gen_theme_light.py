#!/usr/bin/env python3
"""Build public/theme-light.css: a light version of style.css, scoped to <html class="theme-light">.

Used by the light/dark A/B test on /ko/compress-id-photo.html (HANDOFF 2-96). Every rule in
style.css that sets a dark-theme colour is repeated as `:where(html.theme-light) <selector>` with
only those declarations, recoloured. Re-run after changing colours in style.css:
    python3 tools/gen_theme_light.py && python3 tools/bump_versions.py
"""
import os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "public")

# dark colour -> light colour. Text green is darker on white so it stays readable;
# buttons become dark green with white text.
COLORS = {
    "#46e0a0": "#0a875a", "#5dedb4": "#0b9a67", "#0b0d12": "#f5f7fa", "#14181f": "#ffffff",
    "#232a36": "#dde2e9", "#e6e6e6": "#1b2129", "#8a97a8": "#5a6575", "#062a1c": "#ffffff",
    "#333d4d": "#c9d0d9", "#10141b": "#f7f9fb", "#15202b": "#eef7f3", "#0e1117": "#f3f5f8",
    "#6b7788": "#6a7585", "#10231c": "#e6f6ee", "#ffcf6e": "#9a6a00", "#24503f": "#a6d9c1",
    "#1d1a10": "#fff6dd", "#4d4220": "#ecd38c", "#ffd479": "#8a6100", "#ff7a7a": "#cc3333",
    "#ffb3b3": "#e05555", "#2b3444": "#c9d0d9", "#0f1f1a": "#eaf7f0", "#121a22": "#f7f9fb",
    "#1b4a3a": "#dff4ea", "#13241f": "#eef8f3", "#141a24": "#f7f9fb", "#285744": "#b6e0cc",
    "#161b23": "#f1f4f7", "#2a2210": "#fff4dc",
}
RGBA = {
    "rgba(0,0,0,0.4)": "rgba(16,24,40,0.08)", "rgba(0, 0, 0, 0.45)": "rgba(16,24,40,0.12)",
    "rgba(0, 0, 0, 0.35)": "rgba(16,24,40,0.12)", "rgba(11, 13, 18, 0.94)": "rgba(255,255,255,0.96)",
    "rgba(70, 224, 160, 0.3)": "rgba(10,135,90,0.25)",
}
HEX = re.compile(r"#[0-9a-fA-F]{6}\b")

# Rules that live in the page's own <style> (compress-image.html and the pages built from it).
# That <style> comes after theme-light.css, so these keep the full html.theme-light weight.
PAGE_EXTRA = """
html.theme-light .imglist .thumb { background: #f3f5f8; }
html.theme-light .imglist .meta .warn { color: #9a6a00; }
"""


def recolor(decl):
    if re.fullmatch(r"\s*color:\s*#fff\s*", decl):          # white text on a dark card
        return " color: #111827"
    out = HEX.sub(lambda m: COLORS.get(m.group(0).lower(), m.group(0)), decl)
    for a, b in RGBA.items():
        out = out.replace(a, b)
    return out if out != decl else None


def split_top(s, sep):
    """Split on sep outside brackets/parentheses."""
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return parts


def scope(selector):
    # :where() adds no specificity, so each override ties with its original and wins only by
    # coming later (theme-light.css loads right after style.css). States such as .drop:hover
    # therefore still beat the plain .drop override, as they do in the dark theme.
    # The variables need real weight to beat :root.
    out = []
    for sel in split_top(selector, ","):
        sel = sel.strip()
        if sel.startswith(":root"):
            out.append("html.theme-light" + sel[5:])
        elif re.match(r"html\b", sel):
            out.append(":where(html.theme-light)" + sel[4:])
        else:
            out.append(":where(html.theme-light) " + sel)
    return ", ".join(out)


def blocks(css):
    """Yield (prelude, body) for each top-level block."""
    i = 0
    while True:
        j = css.find("{", i)
        if j < 0:
            return
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        yield css[i:j].strip(), css[j + 1:k - 1]
        i = k


def convert(css, indent=""):
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith("@keyframes"):
            continue
        if prelude.startswith("@"):
            inner = convert(body, indent + "   ")
            if inner:
                out.append(f"{indent}{prelude} {{\n" + "\n".join(inner) + f"\n{indent}}}")
            continue
        decls = [recolor(d) for d in split_top(body, ";") if d.strip()]
        decls = [d.strip() for d in decls if d]
        if decls:
            out.append(f"{indent}{scope(prelude)} {{ " + "; ".join(decls) + "; }")
    return out


def main():
    css = open(os.path.join(ROOT, "style.css")).read()
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    rules = convert(css)
    head = "/* Generated by tools/gen_theme_light.py from style.css. Do not edit by hand. */\n"
    open(os.path.join(ROOT, "theme-light.css"), "w").write(head + "\n".join(rules) + "\n" + PAGE_EXTRA.lstrip())
    print(f"theme-light.css: {len(rules)} rules")


if __name__ == "__main__":
    main()
